# Telegram Credentials Loader (Optional alert channel)
def get_telegram_creds():
    token = os.environ.get('TELEGRAM_BOT_TOKEN')
    chat_id = os.environ.get('TELEGRAM_CHAT_ID')
    return token, chat_id

TG_TOKEN, TG_CHAT_ID = get_telegram_creds()

def send_telegram_alert(title: str, body: str, username: str = None):
    """ارسال فوری نوتیفیکیشن به ادمین در صورت لیدهای با پتانسیل بالا"""
    if not TG_TOKEN or not TG_CHAT_ID:
        return
    try:
        ctx = ssl._create_unverified_context()
        text = f"🚨 *{title}*\n\n"
        if username:
            text += f"👤 کاربر اینستاگرام: @{username}\n🔗 دایرکت: [ورود به چت](https://ig.me/m/{username})\n\n"
        text += f"💬 پیام: {body}\n\n🤖 پیج: @nextmind.hq"
        
        url = f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage"
        data = urllib.parse.urlencode({
            "chat_id": TG_CHAT_ID,
            "text": text,
            "parse_mode": "Markdown",
            "disable_web_page_preview": "true"
        }).encode("utf-8")
        req = urllib.request.Request(url, data=data)
        urllib.request.urlopen(req, context=ctx, timeout=8)
    except Exception as e:
        print(f"[Telegram Alert Error] {e}")

